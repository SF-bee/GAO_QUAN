#include <bits/stdc++.h>

int T;
int n, a1, a2, a3;

void sol() { std::cin >> n >> a1 >> a2 >> a3; }

int main() {
    std::cin.tie(0)->sync_with_stdio(0);

    while (T--)
        sol();
    return 0;
}
/*
注意到排列其实是固定的，因为可以重命名节点让某个合法的树存在这样的排列
那么问题就变成了
求出一棵树，满足相邻编号距离为1，2，3的点恰好有a1,a2,a3个
距离为 1 的点是很严格的，必须要直接连边，还得是相邻节点连边
所以可以枚举哪些点直接连边，
这样会形成若干个连通块，我们需要用剩下的边把这些连通块连起来
看回那个排列，如果已经确认了直连的边，那么剩下没有连边的相邻编号一定不能连，不然是不合法的

*/